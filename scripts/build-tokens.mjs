/* ----------------------------------------------------------------- model */

const dashed = (vars) => Object.fromEntries(Object.entries(vars).map(([name, value]) => [`--${name}`, value]));

function buildModel(tokens) {
  const { base, modifiers } = tokens;
  const { theme, ...otherModifiers } = modifiers;
  const themeNames = Object.keys(theme.contexts);
  const hexByTheme = themeColors(tokens);

  const colorVars = (context) =>
    Object.fromEntries([...theme.contexts[context]].filter(([path]) => path.startsWith("color.")).map(([path, token]) => [names(path).cssVar, cssValue(path, token)]));
  const colorPaths = [...theme.contexts[theme.default].keys()].filter((path) => path.startsWith("color."));
  for (const context of themeNames) {
    const paths = [...theme.contexts[context].keys()].filter((path) => path.startsWith("color."));
    if (paths.join() !== colorPaths.join()) throw new Error(`theme "${context}" must define the same colour tokens, in the same order, as "${theme.default}"`);
  }

  // :root values that do not depend on the theme.
  const rootVars = {};
  for (const [path, token] of base) {
    const { cssVar, alias } = names(path);
    if (!cssVar) continue;
    rootVars[cssVar] = cssValue(path, token);
    if (alias) rootVars[alias] = cssValue(path, token);
  }

  // Tailwind `@theme inline`: every key points at a custom property so subtree overrides re-evaluate.
  const themeVars = {};
  for (const path of colorPaths) themeVars[names(path).theme] = `var(--${names(path).cssVar})`;
  for (const [path, token] of base) {
    const { cssVar, theme: themeKey } = names(path);
    if (!themeKey) continue;
    themeVars[themeKey] = cssVar ? `var(--${cssVar})` : cssValue(path, token);
    const leading = token.extensions?.["dev.yorha"]?.leading;
    if (leading) themeVars[`${themeKey}--line-height`] = `var(--${names(`font.leading.${leading}`).cssVar})`;
  }

  // density / motion: every context re-declares the tokens any context overrides (the default context restores base).
  const modifierBlocks = {};
  for (const [name, modifier] of Object.entries(otherModifiers)) {
    const overridden = [...base.keys()].filter((path) => Object.values(modifier.contexts).some((context) => context.has(path)));
    modifierBlocks[name] = Object.fromEntries(
      Object.entries(modifier.contexts).map(([context, map]) => {
        const vars = {};
        for (const path of overridden) {
          const value = cssValue(path, map.get(path) ?? base.get(path));
          const { cssVar, alias, theme: themeKey, mirror } = names(path);
          vars[cssVar] = value;
          if (alias) vars[alias] = value;
          if (mirror) vars[themeKey] = value;
        }
        return [context, vars];
      }),
    );
  }

  const scheme = (context) => (relativeLuminance(hexByTheme[context].bg) < 0.2 ? "dark" : "light");
  const focusRing = { outline: "var(--yorha-ring-width) solid var(--yorha-ring)", "outline-offset": "var(--yorha-ring-offset)" };

  // Registry `css` field (shadcn object form). The stylesheet below is rendered from this same object.
  const css = {};
  for (const { pkg, files } of FONTS) for (const file of files) css[`@import "${pkg}/${file}"`] = {};
  css[`@custom-variant dark (${DARK_VARIANT})`] = {};
  css[":root"] = { "color-scheme": scheme(theme.default), ...dashed(rootVars) };
  css[".dark"] = { "color-scheme": "dark" };
  for (const context of themeNames) {
    css[`[data-theme=${context}]`] = {
      "color-scheme": scheme(context),
      ...dashed(colorVars(context)),
      // Heading text-shadow is decoration: a 2px offset smears glyphs, so the strict-contrast theme drops it.
      ...(context === "high-contrast" ? { "--yorha-text-shadow": "none" } : {}),
    };
  }
  for (const [context, vars] of Object.entries(modifierBlocks.density)) css[`[data-density=${context}]`] = dashed(vars);
  // Language leading: CJK gets the roomier body leading; Latin keeps the base value (a lang="en" island inside a ko page resets it).
  css[":lang(ko), :lang(ja)"] = { "--yorha-leading-body": "var(--yorha-leading-body-cjk)" };
  css[":lang(en)"] = { "--yorha-leading-body": cssValue("font.leading.body", base.get("font.leading.body")) };
  css["@media (prefers-reduced-motion: reduce)"] = { ":root:not([data-motion=full])": dashed(modifierBlocks.motion.reduced) };
  for (const [context, vars] of Object.entries(modifierBlocks.motion)) css[`[data-motion=${context}]`] = dashed(vars);
  css["@utility yorha-focus"] = focusRing;
  css["@utility yorha-tabular"] = { "font-variant-numeric": "tabular-nums" };
  css["@utility yorha-break"] = { "overflow-wrap": "anywhere", "word-break": "normal" };
  Object.assign(css, MOTION_CSS);
  // Forced colours (Windows contrast themes): the UA replaces background-color with Canvas and fill/stroke with text colours,
  // so fills built from bg-yorha-ink and SVG marks disappear. Unlayered on purpose: it must beat the utilities layer.
  // forced-color-adjust: none is set only on the elements that paint a state, and they take system colours.
  const selectedFill = { "forced-color-adjust": "none", "background-color": "Highlight", color: "HighlightText" };
  css["@media (forced-colors: active)"] = {
    ":root, [data-theme]": { "--yorha-text-shadow": "none" },
    // Filled bars (progress, meter, tab indicator) and every control state that fills with ink.
    ".bg-yorha-ink": selectedFill,
    "[role=switch][data-checked], [role=checkbox][data-checked], [role=checkbox][data-indeterminate], [role=tab][data-active], [role=tab][aria-selected=true], [data-pressed]": selectedFill,
    // Switch thumb and checked radio dot paint with currentColor; keep it the control's own text colour, not a forced Canvas.
    "[role=switch] > span, [role=radio][data-checked] > span": { "forced-color-adjust": "none", "background-color": "currentColor" },
    "[role=radio][data-checked]": { "forced-color-adjust": "none", color: "Highlight", "border-color": "Highlight" },
    // Status markers and SVG marks (timeline).
    ".bg-yorha-alert-ui": { "forced-color-adjust": "none", "background-color": "CanvasText" },
    ".fill-yorha-ink": { "forced-color-adjust": "none", fill: "Highlight" },
    ".fill-yorha-on-ink": { "forced-color-adjust": "none", fill: "HighlightText" },
    ".stroke-yorha-bg": { "forced-color-adjust": "none", stroke: "Canvas" },
    ".stroke-yorha-alert-ui": { "forced-color-adjust": "none", stroke: "CanvasText" },
    ".stroke-yorha-ring": { "forced-color-adjust": "none", stroke: "Highlight" },
  };
  css["@layer base"] = {
    // Mobile: no iOS landscape font inflation, no grey tap flash, no double-tap zoom delay on controls (sliders keep their own touch handling).
    html: { "-webkit-text-size-adjust": "100%", "text-size-adjust": "100%" },
    body: {
      "-webkit-tap-highlight-color": "transparent",
      "background-color": "var(--yorha-bg)",
      color: "var(--yorha-fg)",
      "font-family": "var(--yorha-font-sans)",
      "font-size": "var(--yorha-text-base)",
      "line-height": "var(--yorha-leading-body)",
      "letter-spacing": "var(--yorha-tracking-body)",
      "word-break": "keep-all",
      "overflow-wrap": "break-word",
    },
    ":where(a[href], button, summary, label, select, textarea, input:not([type=range]), [role=button], [role=tab], [role=checkbox], [role=radio], [role=switch], [role=menuitem], [role=option], [role=combobox])": { "touch-action": "manipulation" },
    // Never on :root: a font-size there would rescale every rem (and the 16px spacing maths); body carries it for a root density.
    "[data-density]:not(:root)": { "font-size": "var(--yorha-text-base)" },
    ":lang(ko)": { "word-break": "keep-all" },
    ":lang(ja)": { "font-family": "var(--yorha-font-sans-ja)", "word-break": "normal" },
    // Long-string safety net: keep-all stays for Korean prose, but links and code may break anywhere rather than overflow.
    "a, code": { "overflow-wrap": "anywhere" },
    // Table cells break only at word boundaries: `anywhere` shrinks min-content to one glyph and collapses the columns at 320px.
    "td, th": { "overflow-wrap": "break-word" },
    ".yorha-prose": { "max-width": "var(--yorha-measure)" },
    ".yorha-prose p + p": { "margin-top": "var(--yorha-paragraph-gap)" },
    "[data-theme]": { color: "var(--yorha-fg)" },
    ":focus-visible": focusRing,
    ...MOTION_KEYFRAMES,
  };

  return {
    tokens,
    themeNames,
    hexByTheme,
    colorPaths,
    modifierBlocks,
    cssVars: { theme: themeVars, light: colorVars(theme.default), dark: colorVars("dark") },
    css,
  };
}

/* --------------------------------------------------------------- outputs */

function renderRules(rules, indent = "") {
  let out = "";
  for (const [key, value] of Object.entries(rules)) {
    if (typeof value === "string") out += `${indent}${key}: ${value};\n`;
    else if (key.startsWith("@") && Object.keys(value).length === 0) out += `${indent}${key};\n`;
    else out += `${indent}${key} {\n${renderRules(value, `${indent}  `)}${indent}}\n`;
  }
  return out;
}

function renderCss({ cssVars, css }) {
  const isStatement = ([key, value]) => key.startsWith("@") && Object.keys(value).length === 0;
  const statements = Object.entries(css).filter(isStatement);
  const blocks = Object.entries(css).filter((entry) => !isStatement(entry));
  return [
    `/* ${HEADER} */\n${renderRules(Object.fromEntries(statements))}`,
    renderRules({ ":root": dashed(cssVars.light) }),
    renderRules({ ".dark": dashed(cssVars.dark) }),
    renderRules({ "@theme inline": dashed(cssVars.theme) }),
    ...blocks.map(([key, value]) => renderRules({ [key]: value })),
  ].join("\n");
}

function renderRegistry({ cssVars, css }) {
  const { devDependencies } = readJson("package.json");
  const dependencies = FONTS.map(({ pkg }) => {
    if (!devDependencies[pkg]) throw new Error(`font package ${pkg} is not pinned in package.json`);
    return `${pkg}@${devDependencies[pkg]}`;
  });
  const item = {
    name: "base",
    type: "registry:base",
    extends: "none",
    title: "YoRHa base",
    description: "Design tokens, four themes (light, dark, authentic, high-contrast), density, motion and OFL font faces for the YoRHa registry.",
    dependencies,
    cssVars,
    css,
    docs: "Unofficial fan project, not affiliated with Square Enix or PlatinumGames; non-commercial. Set data-theme, data-density and data-motion on <html> or on a subtree. Generated from tokens/*.tokens.json by `pnpm tokens:build`; do not edit by hand.",
  };
  return `${JSON.stringify({ $schema: "https://ui.shadcn.com/schema/registry.json", items: [item] }, null, 2)}\n`;
}

function renderDocs({ tokens, themeNames, hexByTheme, colorPaths, modifierBlocks }) {
  const { base, modifiers } = tokens;
  const list = (prefix) =>
    [...base]
      .filter(([path]) => path.startsWith(prefix))
      .map(([path, token]) => {
        const { cssVar, alias, theme: themeKey } = names(path);
        return {
          name: path.slice(prefix.length),
          cssVar: cssVar ? `--${cssVar}` : "",
          alias: alias ? `--${alias}` : "",
          utility: utility(themeKey),
          value: cssValue(path, token),
          description: token.description ?? "",
        };
      });
  const colors = Object.fromEntries(
    themeNames.map((theme) => [
      theme,
      colorPaths.map((path) => {
        const token = modifiers.theme.contexts[theme].get(path);
        return { name: path.slice("color.".length), cssVar: `--${names(path).cssVar}`, utility: utility(names(path).theme), hex: token.value.hex, value: cssValue(path, token), description: token.description ?? "" };
      }),
    ]),
  );
  const contrast = Object.fromEntries(
    themeNames.map((theme) => {
      const thresholds = THRESHOLDS[theme];
      const rows = checkPairs(hexByTheme[theme], thresholds ?? THRESHOLDS[modifiers.theme.default]);
      return [theme, { enforced: Boolean(thresholds), rows: rows.map((row) => ({ ...row, ratio: Math.floor(row.ratio * 100) / 100 })) }];
    }),
  );
  /** Adds the token's value in each data-motion mode (full / reduced / off). */
  const withMotionModes = (token) => ({
    ...token,
    ...Object.fromEntries(Object.entries(modifierBlocks.motion).map(([context, vars]) => [context, vars[token.cssVar.slice(2)] ?? token.value])),
  });
  const docs = {
    themes: themeNames,
    defaultTheme: modifiers.theme.default,
    colors,
    fontFamilies: list("font.family."),
    fontWeights: list("font.weight."),
    fontSizes: list("font.size.").map((size) => ({ ...size, lineHeight: cssValue("", base.get(`font.leading.${base.get(`font.size.${size.name}`).extensions["dev.yorha"].leading}`)) })),
    leading: list("font.leading."),
    tracking: list("font.tracking."),
    readability: [...list("font.measure"), ...list("font.paragraph-gap")],
    spacing: list("spacing."),
    density: Object.fromEntries(Object.entries(modifierBlocks.density).map(([context, vars]) => [context, vars["yorha-spacing"]])),
    radius: list("radius."),
    borders: list("border."),
    shadows: list("shadow."),
    motion: {
      durations: list("motion.duration.").map(withMotionModes),
      easings: list("motion.easing."),
      parameters: list("motion.")
        .filter((token) => !/^(duration|easing)\./.test(token.name))
        .map(withMotionModes),
      utilities: MOTION_UTILITIES,
    },
    zIndex: list("z."),
    contrast,
  };
  return `// ${HEADER}\nexport const tokens = ${JSON.stringify(docs, null, 2)} as const;\n\nexport type ThemeName = (typeof tokens.themes)[number];\nexport type DensityName = keyof typeof tokens.density;\n`;
}

/** Pure: output path -> file content. */
export function generate() {
  const model = buildModel(loadTokens());
  return {
    [OUTPUTS.css]: renderCss(model),
    [OUTPUTS.registry]: renderRegistry(model),
    [OUTPUTS.docs]: renderDocs(model),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [path, content] of Object.entries(generate())) {
    mkdirSync(dirname(join(ROOT, path)), { recursive: true });
    writeFileSync(join(ROOT, path), content);
    console.log(`tokens: wrote ${path}`);
  }
}
