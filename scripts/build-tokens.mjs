/* ------------------------------------------------------------------ load */

function flatten(node, path = [], type = undefined, out = new Map()) {
  const inherited = node.$type ?? type;
  if ("$value" in node) {
    out.set(path.join("."), { type: inherited, value: node.$value, description: node.$description, extensions: node.$extensions });
    return out;
  }
  for (const [key, child] of Object.entries(node)) if (!key.startsWith("$")) flatten(child, [...path, key], inherited, out);
  return out;
}

function loadSources(sources) {
  const merged = new Map();
  for (const { $ref } of sources) for (const [path, token] of flatten(readJson(join(TOKENS_DIR, $ref)))) merged.set(path, token);
  return merged;
}

/** Reads the DTCG resolver: one base set plus the theme / density / motion modifiers and their contexts. */
export function loadTokens() {
  const resolver = readJson(join(TOKENS_DIR, RESOLVER));
  const base = new Map();
  for (const set of Object.values(resolver.sets)) for (const [path, token] of loadSources(set.sources)) base.set(path, token);
  const modifiers = {};
  for (const [name, modifier] of Object.entries(resolver.modifiers)) {
    modifiers[name] = {
      default: modifier.default,
      contexts: Object.fromEntries(Object.entries(modifier.contexts).map(([context, sources]) => [context, loadSources(sources)])),
    };
  }
  return { base, modifiers };
}

/** theme -> colour token name -> DTCG colour value */
export function themeColorTokens(tokens) {
  return Object.fromEntries(
    Object.entries(tokens.modifiers.theme.contexts).map(([theme, map]) => [
      theme,
      Object.fromEntries([...map].filter(([path]) => path.startsWith("color.")).map(([path, token]) => [path.slice("color.".length), token.value])),
    ]),
  );
}

/** theme -> colour token name -> hex fallback */
export function themeColors(tokens) {
  return Object.fromEntries(
    Object.entries(themeColorTokens(tokens)).map(([theme, byName]) => [theme, Object.fromEntries(Object.entries(byName).map(([name, value]) => [name, value.hex]))]),
  );
}

