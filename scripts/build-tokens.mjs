// Token path -> CSS names. cssVar: --yorha-* custom property; alias: unprefixed twin (--motion-*, --menu-rule);
// theme: Tailwind `@theme inline` key; mirror: also re-declare the theme key inside modifier blocks.
const RULES = [
  [/^color\.(.+)$/, (k) => ({ cssVar: `yorha-${k}`, theme: `color-yorha-${k}` })],
  [/^font\.family\.(.+)$/, (k) => ({ cssVar: `yorha-font-${k}`, theme: k === "sans" ? "font-yorha" : `font-yorha-${k.replace(/^sans-/, "")}` })],
  [/^font\.weight\.(.+)$/, (k) => ({ cssVar: `yorha-font-weight-${k}`, theme: `font-weight-yorha-${k}` })],
  [/^font\.size\.(.+)$/, (k) => ({ cssVar: `yorha-text-${k}`, theme: `text-yorha-${k}` })],
  [/^font\.leading\.(.+)$/, (k) => ({ cssVar: `yorha-leading-${k}`, theme: `leading-yorha-${k}` })],
  [/^font\.measure$/, () => ({ cssVar: "yorha-measure" })],
  [/^font\.paragraph-gap$/, () => ({ cssVar: "yorha-paragraph-gap" })],
  [/^font\.tracking\.(.+)$/, (k) => ({ cssVar: `yorha-tracking-${k}`, theme: `tracking-yorha-${k}` })],
  [/^spacing\.base$/, () => ({ cssVar: "yorha-spacing", theme: "spacing", mirror: true })],
  [/^spacing\.grid$/, () => ({ cssVar: "yorha-grid-size" })],
  [/^radius\.none$/, () => ({ cssVar: "yorha-radius", theme: "radius-yorha" })],
  [/^border\.width\.(.+)$/, (k) => ({ cssVar: k === "thin" ? "yorha-border-width" : `yorha-border-width-${k}` })],
  [/^border\.ring\.(.+)$/, (k) => ({ cssVar: `yorha-ring-${k}` })],
  [/^border\.menu-rule$/, () => ({ cssVar: "yorha-menu-rule", alias: "menu-rule" })],
  [/^shadow\.text$/, () => ({ cssVar: "yorha-text-shadow", theme: "text-shadow-yorha" })],
  [/^shadow\.(.+)$/, (k) => ({ theme: `shadow-yorha-${k}` })],
  [/^motion\.duration\.(.+)$/, (k) => ({ cssVar: `yorha-motion-${k}`, alias: `motion-${k}` })],
  [/^motion\.easing\.(.+)$/, (k) => ({ cssVar: k === "standard" ? "yorha-ease" : `yorha-ease-${k}`, theme: k === "standard" ? "ease-yorha" : `ease-yorha-${k}` })],
  [/^motion\.(.+)$/, (k) => ({ cssVar: `yorha-motion-${k.replaceAll(".", "-")}`, alias: `motion-${k.replaceAll(".", "-")}` })],
  [/^z\.(.+)$/, (k) => ({ cssVar: `yorha-z-${k}` })],
];

function names(path) {
  for (const [pattern, toNames] of RULES) {
    const match = pattern.exec(path);
    if (match) return toNames(match[1]);
  }
  throw new Error(`no naming rule for token "${path}"`);
}

/** Tailwind class a theme key produces (colours take a bg-/text-/border- prefix, so they return the suffix). */
function utility(themeKey) {
  if (!themeKey || themeKey === "spacing") return "";
  if (themeKey.startsWith("color-")) return themeKey.slice("color-".length);
  if (themeKey.startsWith("font-weight-")) return themeKey.replace("font-weight-", "font-");
  if (themeKey.startsWith("radius-")) return themeKey.replace("radius-", "rounded-");
  return themeKey;
}

const dimension = ({ value, unit }) => `${value}${unit}`;

function cssValue(path, token) {
  const { type, value, extensions } = token;
  switch (type) {
    case "color": {
      const [l, c, h] = value.components;
      return value.alpha === undefined ? `oklch(${l} ${c} ${h})` : `oklch(${l} ${c} ${h} / ${value.alpha})`;
    }
    case "dimension":
    case "duration":
      return dimension(value);
    case "fontFamily":
      return value.map((family) => (GENERIC_FAMILIES.has(family) ? family : `"${family}"`)).join(", ");
    case "fontWeight":
      return String(value);
    case "number":
      return `${value}${extensions?.["dev.yorha"]?.unit ?? ""}`;
    case "cubicBezier":
      return `cubic-bezier(${value.join(", ")})`;
    case "shadow": {
      const reference = /^\{(.+)\}$/.exec(value.color);
      if (!reference) throw new Error(`${path}: shadow colour must reference a colour token`);
      // text-shadow has no spread; the colour stays a var() so it follows data-theme on subtrees.
      const lengths = [value.offsetX, value.offsetY, value.blur, ...(path === "shadow.text" ? [] : [value.spread])];
      return `${lengths.map(dimension).join(" ")} var(--${names(reference[1]).cssVar})`;
    }
    default:
      throw new Error(`${path}: unsupported $type "${type}"`);
  }
}

